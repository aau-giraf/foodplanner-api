using Dapper;

using FoodplannerDataAccessSql;

using FoodplannerDataAccessSql.Lunchbox;

using FoodplannerModels.Lunchbox;

namespace Test.RepositoryTests;

public class IngredientRepositoryTests
{
    private readonly PostgreSQLConnectionFactory _connectionFactory;

    // Creates a connection factory for the separate PostgreSQL test database.
    // This prevents repository tests from modifying the normal development database.
    public IngredientRepositoryTests()
    {
        _connectionFactory = new PostgreSQLConnectionFactory(
            "localhost",
            "7654",
            "giraf_test",
            "postgres",
            "postgres"
        );
    }

    [Fact]
    public async Task GetByIdAsync_ShouldReturnIngredient_WhenIngredientExists()
    {
        // Arrange

        // Create the repository using the test database connection.
        var repository = new IngredientRepository(_connectionFactory);

        // Stores the temporary user ID and ingredient ID so they can
        // be used during the test and removed afterwards.
        int testUserId;
        int? ingredientId = null;

        // An ingredient must reference an existing user, so a temporary
        // user is inserted into the test database before creating the ingredient.
        using (var connection = _connectionFactory.Create())
        {
            connection.Open();

            testUserId = await connection.QuerySingleAsync<int>(
                """
                INSERT INTO users
                    (first_name, last_name, email, password, role, role_approved)
                VALUES
                    ('jens', 'tester', @Email, 'password', 'Parent', true)
                RETURNING id
                """,

                // A unique email is generated to avoid conflicts between test runs.
                new { Email = $"ingredient-test-{Guid.NewGuid()}@test.dk" }
            );
        }

        try
        {
            // Create the ingredient that will be inserted and retrieved by the test.
            var ingredient = new Ingredient
            {
                Id = 1,
                Name = "Test Ingredient",
                User_id = testUserId,
                Food_image_id = null
            };

            // Insert the ingredient and store the ID generated by PostgreSQL.
            ingredientId = await repository.InsertAsync(ingredient);

            // Act

            // Retrieve the ingredient again using the generated ID.
            var result = await repository.GetByIdAsync(ingredientId.Value);

            // Assert

            // Verify that an ingredient was returned and that its values
            // match the values that were originally inserted.
            Assert.NotNull(result);
            Assert.Equal(ingredientId.Value, result.Id);
            Assert.Equal("Test Ingredient", result.Name);
            Assert.Equal(testUserId, result.User_id);
            Assert.Null(result.Food_image_id);
        }
        finally
        {
            // Cleanup
            // The finally block ensures that test data is removed even if
            // one of the assertions above fails.

            using var connection = _connectionFactory.Create();
            connection.Open();

            // Only attempt to delete the ingredient if it was successfully inserted.
            if (ingredientId != null)
            {
                await connection.ExecuteAsync(
                    "DELETE FROM ingredients WHERE id = @Id",
                    new { Id = ingredientId }
                );
            }

            // Delete the temporary user after the ingredient, since the
            // ingredient references the user through a foreign key.
            await connection.ExecuteAsync(
                "DELETE FROM users WHERE id = @Id",
                new { Id = testUserId }
            );
        }
    }
}